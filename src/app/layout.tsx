import type { Metadata } from "next";
import { connection } from "next/server";
import { Geist, Geist_Mono } from "next/font/google";
import StoryblokProvider from "@/components/StoryblokProvider";
import BootstrapClient from "@/components/BootstrapClient";
import { AuthProvider } from "@/context/AuthContext";
import HcpPopup from "@/components/layout/HcpPopup";
import Header from "@/components/layout/Header";
import { getStoryblokApi, contentVersion } from "@/lib/storyblok";
import { renderRichText } from "@storyblok/react/rsc";
import "./globals.scss";

// The root layout fetches Storyblok config (header, popup) at request time,
// so every route — including the auto-generated 404 page — renders
// dynamically instead of being prerendered at build time.
export const instant = false;

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Arrotex Eczema Patient",
  description: "Generated by create next app",
};

// Fetch the global "popup" story once; it holds site-wide config such as
// the HCP leaving-site popup texts. Renders nothing when it is missing.
async function getHcpPopupProps() {
  try {
    await connection();
    const { data } = await getStoryblokApi().get("cdn/stories/popup", {
      version: contentVersion,
    });
    const c = data?.story?.content ?? {};
    const text = c.hcpText;
    // hcpUrl accepts a plain string or a Storyblok link field object
    const url =
      typeof c.hcpUrl === "string"
        ? c.hcpUrl
        : c.hcpUrl?.cached_url || c.hcpUrl?.url || "";
    return {
      title: c.hcpTitle || undefined,
      textHtml:
        typeof text === "string" ? text : renderRichText(text) || undefined,
      continueUrl: url || undefined,
      cancelText: c.hcpCancelText || undefined,
      continueText: c.hcpContinueText || undefined,
    };
  } catch {
    return null;
  }
}

// Fetch the global "header" story; the header is configured once there and
// rendered from the layout on every page.
async function getHeaderBlok() {
  try {
    await connection();
    const { data } = await getStoryblokApi().get("cdn/stories/header", {
      version: contentVersion,
    });
    return data?.story?.content ?? null;
  } catch {
    return null;
  }
}

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const [hcpPopup, headerBlok] = await Promise.all([
    getHcpPopupProps(),
    getHeaderBlok(),
  ]);
  return (
    <StoryblokProvider>
      <AuthProvider>
        <html
          lang="en"
          className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
        >
          <body className="min-h-full flex flex-col">
            {/* Adobe Fonts (Typekit)：New Hero */}
            <link rel="preconnect" href="https://use.typekit.net" crossOrigin="anonymous" />
            <link rel="stylesheet" href="https://use.typekit.net/cus4qru.css" precedence="default" />
            <BootstrapClient />
            {headerBlok && <Header blok={headerBlok} />}
            {hcpPopup && <HcpPopup {...hcpPopup} />}
            {children}
          </body>
        </html>
      </AuthProvider>
    </StoryblokProvider>
  );
}
